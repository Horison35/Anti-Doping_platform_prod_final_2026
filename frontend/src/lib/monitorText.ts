// Причёсываем выжимку АД-Монитора для отображения — только формат, не содержание.
// Пайплайн (monitor/load_digest.py) собирает summary из полей контракта
// (violation; орган: X; срок: Y) по шаблону, рассчитанному на дисквалификации.
// Для категорий policy/event, где реального нарушения нет, LLM честно пишет
// "н/д — <пояснение>" и "срок: н/д" — фактически верно, но читается как
// техническая заглушка. Здесь только убираем этот шум с готовой строки,
// новый текст не придумываем.
export function cleanSummary(raw: string | null | undefined): string | null {
  if (!raw) return null
  // Без \b: в JS граница слова определена только для ASCII ([A-Za-z0-9_]) —
  // с кириллицей \b между двумя не-ASCII символами никогда не срабатывает
  // (в отличие, например, от Python, где \b по умолчанию юникод-осведомлён).
  let s = raw
    .replace(/;\s*срок:\s*н\/д\.?/gi, "")
    .replace(/;\s*орган:\s*н\/д\.?/gi, "")

  const m = s.match(/^н\/д\s*[—\-:]\s*(.+)$/i)
  if (m) {
    s = m[1]
    s = s.charAt(0).toUpperCase() + s.slice(1)
  }
  return s.trim() || null
}
